const SIMPLIFIED_SET = new Set(SIMPLIFIED_ONLY);

/** 回傳文字中出現的簡體專用字（去重、依出現順序）。 */
export function findSimplified(text: string): string[] {
  const found = new Set<string>();
  for (const char of text) if (SIMPLIFIED_SET.has(char)) found.add(char);
  return [...found];
}
